// --- EAN-13 encoding -------------------------------------------------------

var eanL = [10]string{"0001101", "0011001", "0010011", "0111101", "0100011", "0110001", "0101111", "0111011", "0110111", "0001011"}
var eanG = [10]string{"0100111", "0110011", "0011011", "0100001", "0011101", "0111001", "0000101", "0010001", "0001001", "0010111"}
var eanR = [10]string{"1110010", "1100110", "1101100", "1000010", "1011100", "1001110", "1010000", "1000100", "1001000", "1110100"}
var eanParity = [10]string{"LLLLLL", "LLGLGG", "LLGGLG", "LLGGGL", "LGLLGG", "LGGLLG", "LGGGLL", "LGLGLG", "LGLGGL", "LGGLGL"}

func ean13CheckDigit(digits string) (int, bool) {
	if len(digits) != 12 {
		return 0, false
	}
	sum := 0
	for i, r := range digits {
		if r < '0' || r > '9' {
			return 0, false
		}
		v := int(r - '0')
		if i%2 == 1 {
			sum += v * 3
		} else {
			sum += v
		}
	}
	return (10 - sum%10) % 10, true
}

// ean13Bars returns the black/white module string for a 13-digit EAN-13 code.
func ean13Bars(code string) (string, bool) {
	if len(code) != 13 {
		return "", false
	}
	first := int(code[0] - '0')
	if first < 0 || first > 9 {
		return "", false
	}
	var bars strings.Builder
	bars.WriteString("101")
	for i, r := range code[1:7] {
		d := int(r - '0')
		if d < 0 || d > 9 {
			return "", false
		}
		if eanParity[first][i] == 'L' {
			bars.WriteString(eanL[d])
		} else {
			bars.WriteString(eanG[d])
		}
	}
	bars.WriteString("01010")
	for _, r := range code[7:] {
		d := int(r - '0')
		if d < 0 || d > 9 {
			return "", false
		}
		bars.WriteString(eanR[d])
	}
	bars.WriteString("101")
	return bars.String(), true
}

// isEAN13 reports whether s is exactly 13 digits. The check digit isn't
// re-validated here: barcodes are generated by db.generateEAN13, whose
// weighting the rest of the system trusts, and we only need to know a real
// code has been assigned (vs. a legacy/empty/non-numeric value).
func isEAN13(s string) bool {
	if len(s) != 13 {
		return false
	}
	for i := 0; i < 13; i++ {
		if s[i] < '0' || s[i] > '9' {
			return false
		}
	}
	return true
}

