// An icon missing from iconPaths is a bug (scripts/check-icons.mjs fails the
// build on literal names), but a dynamic name can still slip through. It draws
// a neutral placeholder instead of its name as text, and warns once per name:
// a warning on every render is what used to make the app crawl.
const warnedIcons = new Set()

const mdi = {
  component: props => {
    const path = iconPaths[props.icon] ?? iconPaths['mdi-help-circle-outline']
    if (!iconPaths[props.icon] && !warnedIcons.has(props.icon)) {
      warnedIcons.add(props.icon)
      console.warn(`Icon "${props.icon}" not found in custom MDI icon set`)
    }
    return h(props.tag, null, {
      default: () => [
        h('svg', {
          'xmlns': 'http://www.w3.org/2000/svg',
          'viewBox': '0 0 24 24',
          'role': 'img',
          'aria-hidden': 'true',
          'class': 'v-icon__svg',
        }, [h('path', { d: path })]),
      ],
    })
  },
}

